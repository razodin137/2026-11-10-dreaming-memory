import fs from "node:fs"
import path from "node:path"
import { randomUUID } from "node:crypto"
import { fingerprint, now } from "./db.js"
import { liveNotes, normalizeTopic, remember } from "./notes.js"
import { shared } from "./text.js"

export const MEMORY_DIR = "memory"
export const HEADER = "<!-- generated by mem. write through `mem remember`, never by hand. -->"
export const INDEX = "README.md"
const ENTRY = /^- <!-- mem (\{.*\}) --> (.*)$/
const PLAIN = /^- (?!<!-- mem )(.*)$/
const LOCK_TIMEOUT_MS = Number(process.env.MEM_LOCK_TIMEOUT_MS || 5000)
const LOCK_STALE_MS = Number(process.env.MEM_LOCK_STALE_MS || 30000)

export function memoryDir(project, options = { }) {
  const dir = options.dir || process.env.MEMORY_DIR || path.join(project.path, MEMORY_DIR)
  return path.resolve(dir)
}

export function topicTitle(topic) {
  const title = normalizeTopic(topic).split("-").join(" ")
  return title.charAt(0).toUpperCase() + title.slice(1)
}

export function topicFile(project, topic, options = { }) {
  return path.join(memoryDir(project, options), `${normalizeTopic(topic)}.md`)
}

export function files(project, options = { }) {
  const dir = memoryDir(project, options)
  if (!fs.existsSync(dir)) return [ ]
  return fs.readdirSync(dir)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => path.join(dir, name))
}

export function readTopic(file) {
  if (!fs.existsSync(file)) return { title: null, entries: [ ] }
  const text = fs.readFileSync(file, "utf8")
  const entries = [ ]
  let title = null
  let section = null
  for (const line of text.split("\n")) {
    if (!title && line.startsWith("# ")) {
      title = line.slice(2).trim()
      continue
    }
    if (line.startsWith("## ")) {
      section = line.slice(3).trim()
      continue
    }
    if (section === "Related") continue
    const match = line.match(ENTRY)
    if (match) {
      entries.push({ ...parseMeta(match[1]), body: match[2].trim(), registered: true })
      continue
    }
    const plain = line.match(PLAIN)
    if (plain) entries.push({ body: plain[1].trim(), registered: false })
  }
  return { title, entries }
}

export function renderTopic(topic, entries, related = [ ]) {
  const lines = [
    `# ${topicTitle(topic)}`,
    "",
    HEADER,
    ""
  ]
  if (entries.length === 0) {
    lines.push("_nothing yet_")
  }
  for (const entry of entries) {
    lines.push(renderEntry(entry))
  }
  if (related.length > 0) {
    lines.push("", "## Related", "")
    for (const item of related) {
      lines.push(`- [${topicTitle(item.topic)}](${normalizeTopic(item.topic)}.md)`)
    }
  }
  lines.push("")
  return lines.join("\n")
}

function renderEntry(note) {
  const meta = {
    id: note.id,
    kind: note.kind,
    confidence: Number(Number(note.confidence).toFixed(2)),
    provenance: note.provenance || "",
    topic: normalizeTopic(note.topic),
    version: note.version
  }
  if (note.verified_at) meta.verified_at = note.verified_at
  const lines = [ `- <!-- mem ${JSON.stringify(meta)} --> ${singleLine(note.body)}` ]
  if (note.repro) lines.push(`  - Repro: ${singleLine(note.repro)}`)
  if (note.prevalence) {
    const examples = exampleSessions(note.examples)
    const suffix = examples.length > 0 ? ` (${examples.join(", ")})` : ""
    lines.push(`  - Seen: ${singleLine(note.prevalence)}${suffix}`)
  } else {
    const examples = exampleSessions(note.examples)
    if (examples.length > 0) lines.push(`  - Seen: ${examples.join(", ")}`)
  }
  return lines.join("\n")
}

function exampleSessions(value) {
  if (!value) return [ ]
  let list = value
  if (typeof value === "string") {
    try {
      list = JSON.parse(value)
    } catch {
      return [ ]
    }
  }
  if (!Array.isArray(list)) return [ ]
  return list
    .map((example) => (example && typeof example === "object" ? example.session : example))
    .filter(Boolean)
    .slice(0, 5)
}

export function renderIndex(project, counts) {
  const lines = [
    `# Memory: ${project.slug}`,
    "",
    HEADER,
    "",
    "One file per subject. Agents read these files and write through `mem remember --topic`.",
    ""
  ]
  if (counts.length === 0) lines.push("_nothing yet_")
  for (const item of counts) {
    lines.push(`- [${topicTitle(item.topic)}](${normalizeTopic(item.topic)}.md) — ${item.notes} note${item.notes === 1 ? "" : "s"}`)
  }
  lines.push("")
  return lines.join("\n")
}

export function entriesFor(db, project, topic) {
  return liveNotes(db, { projectId: project.id }).filter((note) => normalizeTopic(note.topic) === normalizeTopic(topic))
}

export function topicCounts(db, project) {
  const groups = new Map()
  for (const note of liveNotes(db, { projectId: project.id })) {
    const topic = normalizeTopic(note.topic)
    const current = groups.get(topic) || { topic, notes: 0 }
    current.notes += 1
    groups.set(topic, current)
  }
  return Array.from(groups.values()).sort((a, b) => a.topic.localeCompare(b.topic))
}

export function relatedFor(db, project, topic) {
  const subject = entriesFor(db, project, topic).map((note) => note.body).join(" ")
  const scored = [ ]
  for (const candidate of topicCounts(db, project)) {
    if (candidate.topic === topic) continue
    const body = entriesFor(db, project, candidate.topic).map((note) => note.body).join(" ")
    const score = shared(subject, body).length
    if (score > 0) scored.push({ topic: candidate.topic, score })
  }
  return scored.sort((a, b) => b.score - a.score || a.topic.localeCompare(b.topic)).slice(0, 4)
}

export function syncTopic(db, project, topic, options = { }) {
  const file = topicFile(project, topic, options)
  return withFileLock(file, () => {
    const content = renderTopic(topic, entriesFor(db, project, topic), relatedFor(db, project, topic))
    writeFileAtomic(file, content)
    return { topic: normalizeTopic(topic), path: file }
  })
}

export function syncTopics(db, project, options = { }) {
  const dir = memoryDir(project, options)
  fs.mkdirSync(dir, { recursive: true })
  const counts = topicCounts(db, project)
  const written = [ ]
  for (const item of counts) written.push(syncTopic(db, project, item.topic, options))

  const wanted = new Set(counts.map((item) => `${normalizeTopic(item.topic)}.md`))
  const stale = [ ]
  for (const file of files(project, options)) {
    const name = path.basename(file)
    if (name === INDEX || wanted.has(name)) continue
    if (!generatedFile(file)) continue
    if (readTopic(file).entries.some((entry) => !entry.registered)) {
      stale.push(file)
      continue
    }
    withFileLock(file, () => fs.rmSync(file, { force: true }))
  }

  const index = path.join(dir, INDEX)
  withFileLock(index, () => writeFileAtomic(index, renderIndex(project, counts)))
  return {
    dir,
    files: [ ...written.map((item) => item.path), index ],
    topics: counts,
    notes: counts.reduce((sum, item) => sum + item.notes, 0),
    stale
  }
}

export function recordNote(db, project, note, options = { }) {
  const topic = normalizeTopic(note.topic)
  const previous = existingTopic(db, project, note)
  const file = topicFile(project, topic, options)
  const result = withFileLock(file, () => {
    const written = remember(db, { ...note, topic })
    const content = renderTopic(topic, entriesFor(db, project, topic), relatedFor(db, project, topic))
    writeFileAtomic(file, content)
    return written
  })
  if (previous && previous !== topic) syncTopics(db, project, options)
  else refreshIndex(db, project, options)
  return { ...result, topic, file }
}

function existingTopic(db, project, note) {
  const scope = note.scope || "project"
  const kind = note.kind || "fact"
  const projectId = scope === "global" ? 0 : note.projectId
  const row = db.prepare(`
    SELECT topic FROM notes
    WHERE scope = ? AND IFNULL(project_id, 0) = ? AND kind = ? AND fingerprint = ? AND retired_at IS NULL
  `).get(scope, projectId, kind, fingerprint(note.body))
  return row ? normalizeTopic(row.topic) : null
}

export function refreshIndex(db, project, options = { }) {
  const dir = memoryDir(project, options)
  fs.mkdirSync(dir, { recursive: true })
  const index = path.join(dir, INDEX)
  const counts = topicCounts(db, project)
  withFileLock(index, () => writeFileAtomic(index, renderIndex(project, counts)))
  return { path: index, topics: counts }
}

export function withFileLock(file, fn) {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const lock = `${file}.lock`
  const started = Date.now()
  let fd = null
  while (fd === null) {
    try {
      fd = fs.openSync(lock, "wx")
    } catch (error) {
      if (error.code !== "EEXIST") throw error
      if (stale(lock)) {
        fs.rmSync(lock, { force: true })
        continue
      }
      if (Date.now() - started > LOCK_TIMEOUT_MS) {
        throw new Error(`timed out waiting for lock: ${lock}`, { cause: error })
      }
      pause(20)
    }
  }
  try {
    fs.writeFileSync(lock, `${process.pid}\n${now()}\n`)
    return fn()
  } finally {
    fs.closeSync(fd)
    fs.rmSync(lock, { force: true })
  }
}

function stale(lock) {
  try {
    return Date.now() - fs.statSync(lock).mtimeMs > LOCK_STALE_MS
  } catch {
    return false
  }
}

function pause(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms)
}

export function writeFileAtomic(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  const temp = `${file}.${process.pid}.${randomUUID()}.tmp`
  fs.writeFileSync(temp, content)
  fs.renameSync(temp, file)
}

function parseMeta(text) {
  try {
    return JSON.parse(text)
  } catch {
    return { }
  }
}

function generatedFile(file) {
  try {
    const head = fs.readFileSync(file, "utf8").slice(0, 200)
    return head.includes("generated by mem")
  } catch {
    return false
  }
}

function singleLine(value) {
  return String(value || "").replace(/\s+/g, " ").trim()
}
